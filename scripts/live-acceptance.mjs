import assert from "node:assert/strict";

const baseUrl = (
  process.env.LIVE_BASE_URL || "https://ai-prototype-advisor-brief.lovable.app"
).replace(/\/$/, "");
const tickers = (process.env.LIVE_TICKERS || "LLY,BA,NVDA,ORCL")
  .split(",")
  .map((ticker) => ticker.trim().toUpperCase())
  .filter(Boolean);
const cooldownMs = Number(process.env.LIVE_COOLDOWN_MS || 4_000);

const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function briefing(ticker) {
  const response = await fetch(
    `${baseUrl}/api/public/advisor-brief?q=${encodeURIComponent(ticker)}&fresh=1`,
    {
      headers: { accept: "text/event-stream" },
      signal: AbortSignal.timeout(240_000),
    },
  );
  assert.equal(response.status, 200, `${ticker}: briefing HTTP ${response.status}`);
  assert.ok(response.body, `${ticker}: missing SSE body`);
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  const events = [];
  let buffer = "";
  const consume = (frame) => {
    const event = frame.match(/^event:\s*(.+)$/m)?.[1];
    const data = frame.match(/^data:\s*(.+)$/m)?.[1];
    if (event && data) events.push({ event, data: JSON.parse(data) });
  };
  for (;;) {
    const { value, done } = await reader.read();
    if (done) break;
    buffer += decoder.decode(value, { stream: true });
    let separator;
    while ((separator = buffer.indexOf("\n\n")) >= 0) {
      consume(buffer.slice(0, separator));
      buffer = buffer.slice(separator + 2);
    }
  }
  const blocks = new Set(events.filter((row) => row.event === "block").map((row) => row.data.name));
  const validation = events.find((row) => row.event === "validation_summary")?.data;
  const failure = events.find((row) => row.event === "research_failed")?.data;
  const done = events.find((row) => row.event === "done")?.data;
  assert.equal(
    failure,
    undefined,
    `${ticker}: ${failure?.code || "briefing failed"} ${failure?.message || ""}`,
  );
  assert.equal(blocks.size, 6, `${ticker}: expected six narrative blocks, received ${blocks.size}`);
  assert.equal(validation?.validatorRan, true, `${ticker}: independent review did not run`);
  assert.equal(validation?.provider, "gemini", `${ticker}: reviewer was not Gemini`);
  assert.equal(
    typeof validation?.supportedPct,
    "number",
    `${ticker}: evidence coverage score missing`,
  );
  assert.equal(done?.researchFailed, false, `${ticker}: completion reported a failed narrative`);
  return {
    ticker,
    blocks: blocks.size,
    claims: validation.claims,
    supportedPct: validation.supportedPct,
    held: validation.excluded,
    elapsedMs: done.totalMs,
  };
}

async function ask(ticker, question, session) {
  const response = await fetch(`${baseUrl}/api/public/advisor-ask`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ ticker, question, session }),
    signal: AbortSignal.timeout(180_000),
  });
  assert.equal(response.status, 200, `Ask HTTP ${response.status}`);
  return response.json();
}

const results = [];
for (const ticker of tickers) {
  if (results.length) await pause(cooldownMs);
  results.push(await briefing(ticker));
  console.log(JSON.stringify(results.at(-1)));
}

await pause(cooldownMs);
const factual = await ask("NVDA", "What does management say about supply?", `live-${Date.now()}`);
assert.equal(factual.provider, "gemini", "Factual follow-up was not generated by Gemini");
assert.ok(
  Array.isArray(factual.sources) && factual.sources.length > 0,
  "Factual follow-up has no filing source",
);
assert.notEqual(factual.verdict, "unavailable", "Factual follow-up was unavailable");

const refusal = await ask("NVDA", "Should I buy this stock?", `live-${Date.now()}`);
assert.equal(refusal.refused, true, "Recommendation request was not refused");
assert.equal(refusal.provider, undefined, "Recommendation refusal should happen before inference");

console.log(
  JSON.stringify(
    {
      baseUrl,
      tickers: results,
      ask: {
        provider: factual.provider,
        sources: factual.sources.length,
        verdict: factual.verdict,
      },
      refusal: refusal.verdict,
    },
    null,
    2,
  ),
);
